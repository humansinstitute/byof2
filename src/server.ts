import {parseNStackConnectionsJSON} from './nstack';
import {ensureDesignLifecycleBackup} from './migration-backup';
import {createManagedNStackTransport} from '../integration/nstack-transport';
import {createManagedNStackFiles} from '../integration/nstack-files';
import {materializePipelineCredentials,materializeGatewayCredential} from './credentials';
import {mkdirSync} from 'node:fs';
import {dirname} from 'node:path';
import {startDispatcher} from './dispatcher';
import {config} from './config';
import {Store} from './store';
import {createApp} from './app';
const cfg=config();mkdirSync(dirname(cfg.database),{recursive:true});materializeGatewayCredential(cfg.database);const store=new Store(cfg.database);ensureDesignLifecycleBackup(store,cfg.database);const app=createApp(store,cfg,{nstackTransport:createManagedNStackTransport(),nstackFiles:createManagedNStackFiles(),nstackConnections:parseNStackConnectionsJSON(process.env.BYO_NSTACK_CONNECTIONS_JSON)});
materializePipelineCredentials(cfg.database);
startDispatcher(store);
Bun.serve({port:cfg.port,hostname:'0.0.0.0',fetch:app.fetch,maxRequestBodySize:12*1024*1024});
console.log(`BYO Freedom ${cfg.version} listening on ${cfg.port}`);
